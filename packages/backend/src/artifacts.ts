import { createReadStream } from "node:fs";
import { mkdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import type { Readable } from "node:stream";
import { GetObjectCommand, PutObjectCommand, S3Client } from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";

export type ArtifactLocation =
  | { kind: "redirect"; url: string }
  | { kind: "stream"; stream: Readable; size: number; contentType: string };

export interface ArtifactStore {
  put(key: string, body: Buffer | string, contentType: string): Promise<void>;
  /** null if the artifact doesn't exist (local store only; S3 just signs). */
  locate(key: string): Promise<ArtifactLocation | null>;
}

const CONTENT_TYPES: Record<string, string> = {
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".json": "application/json",
  ".har": "application/json",
  ".html": "text/plain; charset=utf-8", // never render captured HTML
  ".txt": "text/plain; charset=utf-8",
};

/** Keys are generated by the worker, but validate anyway: `scans/<uuid>/...`, no traversal. */
export function isValidArtifactKey(key: string) {
  return /^scans\/[0-9a-f-]{36}\/[\w.\-/]+$/.test(key) && !key.split("/").includes("..");
}

class LocalStore implements ArtifactStore {
  private root: string;
  constructor(root: string) {
    this.root = path.resolve(root);
  }

  private resolve(key: string) {
    const file = path.resolve(this.root, key);
    if (!file.startsWith(this.root + path.sep)) throw new Error("Invalid artifact key");
    return file;
  }

  async put(key: string, body: Buffer | string) {
    const file = this.resolve(key);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, body);
  }

  async locate(key: string): Promise<ArtifactLocation | null> {
    const file = this.resolve(key);
    try {
      const info = await stat(file);
      if (!info.isFile()) return null;
      const contentType = CONTENT_TYPES[path.extname(file)] ?? "application/octet-stream";
      return { kind: "stream", stream: createReadStream(file), size: info.size, contentType };
    } catch {
      return null;
    }
  }
}

class S3Store implements ArtifactStore {
  private client: S3Client;
  private bucket: string;
  constructor() {
    this.bucket = process.env.S3_BUCKET ?? "ladybug-artifacts";
    this.client = new S3Client({
      endpoint: process.env.S3_ENDPOINT,
      region: process.env.S3_REGION ?? "us-east-1",
      forcePathStyle: true,
      credentials: {
        accessKeyId: process.env.S3_ACCESS_KEY_ID ?? "",
        secretAccessKey: process.env.S3_SECRET_ACCESS_KEY ?? "",
      },
    });
  }

  async put(key: string, body: Buffer | string, contentType: string) {
    await this.client.send(new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: body, ContentType: contentType }));
  }

  async locate(key: string): Promise<ArtifactLocation> {
    const command = new GetObjectCommand({ Bucket: this.bucket, Key: key });
    return { kind: "redirect", url: await getSignedUrl(this.client, command, { expiresIn: 600 }) };
  }
}

export function createArtifactStore(): ArtifactStore {
  if (process.env.ARTIFACT_STORE === "s3") return new S3Store();
  const root = process.env.ARTIFACT_DIR ?? path.resolve(import.meta.dirname, "../../../.artifacts");
  return new LocalStore(root);
}
